@dataclass
class PlannedToolCall:
    """A tool execution step generated by the planner."""

    tool_name: str
    arguments: dict[str, Any] = field(default_factory=dict)
    purpose: str = ""


@dataclass
class PlanResult:
    """The structured planning outcome."""

    archetype: str
    reasoning: str
    tool_calls: list[PlannedToolCall]


class ToolCallSpec(BaseModel):
    """Specification for a single tool invocation generated by the LLM."""

    tool_name: ToolName = Field(..., description="The name of the retrieval tool to execute")
    arguments: dict[str, Any] = Field(default_factory=dict, description="Arguments dictionary for this tool")
    purpose: str = Field(default="", description="1-sentence reason explaining what this tool call gathers")


class AgentPlan(BaseModel):
    """Structured plan returned by the LLM containing direct tool calls."""

    thought_process: str = Field(default="", description="Chain-of-thought analysis of user intent")
    archetype: QueryArchetype = Field(default="factual_lookup", description="Archetype of the query")
    tool_calls: list[ToolCallSpec] = Field(default_factory=list, description="Ordered list of 1-3 tool calls to execute")

    # Legacy fields for backward compatibility with existing test fixtures and mocks
    primary_tool: str | None = None
    arguments: Any = None
    include_secondary_hybrid_search: bool = False
    secondary_search_query: str | None = None


